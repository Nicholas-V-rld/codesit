/*
 * CodeSit — the Express app
 * =========================
 * Builds and returns the whole app: middleware, the API routes (kept in
 * src/routes), and the HTML pages (in /views). This is split out from
 * server.js so tests can build the app in-process — no port to bind, no real
 * network call needed to exercise a route — and drive it directly.
 *
 * server.js is the only thing that actually starts listening. On Vercel
 * nothing listens at all: the platform imports this file (it looks for
 * src/app.js) and hands each request to the app exported below.
 */

const path = require("path");
const fs = require("fs");
const express = require("express");
const session = require("express-session");
const helmet = require("helmet");
const { rateLimit, ipKeyGenerator } = require("express-rate-limit");

const config = require("./config");
const db = require("./db");
const seed = require("./seed");
const DbSessionStore = require("./session-store");
const { requireAuth, homeFor } = require("./middleware/auth");

const authRoutes = require("./routes/auth.routes");
const executeRoutes = require("./routes/execute.routes");
const submissionRoutes = require("./routes/submission.routes");
const examRoutes = require("./routes/exam.routes");
const adminRoutes = require("./routes/admin.routes");

const ROOT = path.join(__dirname, "..");

/*
 * Create the tables and the demo accounts before the first request is
 * handled. Memoised: every request waits on the same promise, which is
 * already settled after the first. A failure (the database unreachable, say)
 * is not memoised, so the next request tries again.
 */
let initPromise = null;
function init() {
  if (!initPromise) {
    initPromise = db.ready().then(seed).then(seed.ensureAdmin).catch((err) => {
      initPromise = null;
      throw err;
    });
  }
  return initPromise;
}

function createApp() {
  const app = express();
  if (config.IS_PRODUCTION) app.set("trust proxy", 1); // so `secure` cookies and client IPs work behind a proxy

  const LANDING_DIST = path.join(ROOT, "landing", "dist");
  const LANDING_INDEX = path.join(LANDING_DIST, "index.html");

  // --- Middleware ---
  /*
   * Security headers. The Content-Security-Policy is switched off because the
   * product pages deliberately load Monaco from a CDN and render student HTML
   * in a sandboxed frame; the rest of helmet's headers (no-sniff, frameguard,
   * referrer policy and friends) all apply.
   */
  app.use(helmet({ contentSecurityPolicy: false, crossOriginEmbedderPolicy: false }));

  app.use(express.json({ limit: "1mb" }));
  app.use(express.urlencoded({ extended: true }));
  /*
   * A malformed JSON body makes express.json() throw synchronously, which
   * Express's default handler turns into a raw HTML stack trace — including
   * this server's own filesystem paths — sent straight to the client. Every
   * route here expects JSON back, so answer the same way: a clean 400.
   */
  app.use((err, req, res, next) => {
    if (err instanceof SyntaxError && "body" in err) {
      return res.status(400).json({ error: "That request wasn't valid JSON." });
    }
    next(err);
  });
  /*
   * Static files. Locally, Express serves public/ itself. On Vercel the
   * platform serves public/ from its CDN before a request ever reaches this
   * app, and express.static() is not used.
   */
  // App CSS/JS win over landing assets where paths collide.
  app.use(express.static(path.join(ROOT, "public")));

  /*
   * The landing page's built files (landing/dist). These are generated by the
   * build, after Vercel has already collected public/ for its CDN, so they
   * are served here explicitly — with sendFile, which works everywhere. The
   * bundles under /assets/ have content hashes in their names, so browsers
   * may cache them for good.
   */
  const LANDING_FILES = new Set(["favicon.svg", "og.svg"]);
  app.get(["/assets/:file", "/:file"], (req, res, next) => {
    const inAssets = req.path.startsWith("/assets/");
    const name = req.params.file;
    if (!inAssets && !LANDING_FILES.has(name)) return next();
    if (!/^[\w.-]+$/.test(name)) return next(); // no path tricks
    const file = path.join(LANDING_DIST, inAssets ? "assets" : "", name);
    res.sendFile(file, { maxAge: inAssets ? "1y" : "1d", immutable: inAssets }, (err) => {
      if (err) next();
    });
  });

  // Everything below needs the database ready.
  app.use((req, res, next) => init().then(() => next(), next));

  /*
   * Sessions are kept in the database, not in memory (src/session-store.js).
   * Restarting the server therefore does not log everyone out mid-exam —
   * which matters a great deal once there is a clock running on a paper.
   */
  app.use(session({
    store: new DbSessionStore(),
    secret: config.SESSION_SECRET,
    resave: false,
    saveUninitialized: false,
    cookie: {
      maxAge: 24 * 60 * 60 * 1000, // 1 day
      httpOnly: true,              // not readable from JavaScript
      sameSite: "lax",             // not sent on cross-site form posts
      secure: config.IS_PRODUCTION, // HTTPS-only once deployed
    },
  }));

  /*
   * Rate limits.
   *
   * A whole computer lab full of students sits behind one shared IP on exam
   * day, so a plain per-IP cap is dangerous here: one mistyped password, or
   * everyone pressing "Run" within the same minute, would lock out the
   * entire room, not just the person responsible. Each limiter below is
   * scoped as close to the actual actor as the request lets it be, so the
   * limit still stops the thing it's meant to stop (repeated guesses
   * against one account; one script hammering the runner) without
   * collateral-damaging classmates on the same network.
   */
  const loginLimiter = rateLimit({
    windowMs: 15 * 60 * 1000,
    max: 20,
    standardHeaders: true,
    legacyHeaders: false,
    // Keyed by the username being attempted, not the caller's IP — so
    // brute-forcing one account is still capped, but a lab full of students
    // logging in around the same time never shares one counter.
    keyGenerator: (req) => (req.body && req.body.username || "").trim().toLowerCase() || ipKeyGenerator(req.ip),
    message: { error: "Too many sign-in attempts on this account. Please wait a few minutes and try again." },
  });
  const registerLimiter = rateLimit({
    windowMs: 15 * 60 * 1000,
    max: 60, // generous: a whole class registering in one sitting, from one IP, is normal
    standardHeaders: true,
    legacyHeaders: false,
    message: { error: "Too many accounts created from this network recently. Please wait a few minutes and try again." },
  });
  const runLimiter = rateLimit({
    windowMs: 60 * 1000,
    max: 40,
    standardHeaders: true,
    legacyHeaders: false,
    // Keyed by the logged-in student, not the IP, for the same reason as
    // above — falls back to IP only for the pre-auth case (no session yet).
    keyGenerator: (req) => (req.session && req.session.userId ? `u${req.session.userId}` : ipKeyGenerator(req.ip)),
    message: { error: "You are running code very quickly. Give it a moment." },
  });

  // --- API routes ---
  app.use("/api/login", loginLimiter);
  app.use("/api/register", registerLimiter);
  app.use("/api/execute", runLimiter);

  app.use("/api", authRoutes);
  app.use("/api", executeRoutes);
  app.use("/api", submissionRoutes);
  app.use("/api", examRoutes);
  app.use("/api", adminRoutes);

  // --- Pages ---
  const page = (file) => path.join(ROOT, "views", file);

  app.get("/", (req, res) => {
    // Logged-in users skip the marketing page.
    if (req.session.userId) {
      return res.redirect(homeFor(req.session.role));
    }
    if (fs.existsSync(LANDING_INDEX)) {
      return res.sendFile(LANDING_INDEX);
    }
    return res
      .status(503)
      .type("text")
      .send("Landing page not built. Run: npm run build");
  });

  app.get("/login", (req, res) => res.sendFile(page("login.html")));
  app.get("/register", (req, res) => res.sendFile(page("register.html")));

  // A page for one role; anyone else is sent to their own home page.
  const rolePage = (role) => (file) => [requireAuth, (req, res) => {
    if (req.session.role !== role) return res.redirect(homeFor(req.session.role));
    res.sendFile(page(file));
  }];
  const studentPage = rolePage(config.ROLES.STUDENT);
  const lecturerPage = rolePage(config.ROLES.LECTURER);
  const adminPage = rolePage(config.ROLES.ADMIN);

  app.get("/student", ...studentPage("student.html"));
  app.get("/exam", ...studentPage("exam.html"));        // sitting a paper
  app.get("/result", ...studentPage("result.html"));    // a marked paper

  app.get("/lecturer", ...lecturerPage("lecturer.html"));
  app.get("/exam-builder", ...lecturerPage("exam-builder.html")); // setting a paper
  app.get("/exam-results", ...lecturerPage("exam-results.html")); // marking & records

  app.get("/admin", ...adminPage("admin.html"));        // accounts, approvals, oversight

  /*
   * Anything that went wrong without a response being sent — most likely the
   * database being unreachable. The details go to the server log, never to
   * the browser.
   */
  // eslint-disable-next-line no-unused-vars
  app.use((err, req, res, next) => {
    console.error(`[error] ${req.method} ${req.originalUrl}:`, err);
    if (res.headersSent) return;
    if (req.originalUrl.startsWith("/api/")) {
      return res.status(500).json({ error: "Something went wrong on the server. Please try again." });
    }
    res.status(500).type("text").send("Something went wrong on the server. Please try again.");
  });

  return app;
}

// The app itself is the export (what Vercel serves); tests build a fresh one
// of their own with createApp().
const app = createApp();
module.exports = app;
module.exports.createApp = createApp;
